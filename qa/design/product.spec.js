const accessibilityRules = ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']

async function checkAccessibility(page) {
  const { violations } = await new AxeBuilder({ page }).withTags(accessibilityRules).analyze()
  expect(violations.map(({ id, nodes }) => ({ id, targets: nodes.map(node => node.target) }))).toEqual([])
}

async function checkViewport(page) {
  const size = await page.evaluate(() => ({
    viewport: document.documentElement.clientWidth,
    content: document.documentElement.scrollWidth,
  }))
  expect(size.content, 'page should fit without horizontal scrolling').toBeLessThanOrEqual(size.viewport + 1)
}

async function capture(page, info, name, options = {}) {
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: info.outputPath(name + '.png'), animations: 'disabled', ...options })
}

test('landing layout and access', async ({ page, site }, info) => {
  await page.goto(site.origin)
  await expect(page.getByRole('heading', { level: 1 })).toContainText('See what a site')
  const heroAction = page.locator('.hero-actions .primary-button')
  const action = await heroAction.boundingBox()
  const image = page.locator('.hero-image img')
  await expect.poll(() => image.evaluate(item => item.naturalWidth)).toBeGreaterThan(0)
  const hero = await image.boundingBox()
  expect(action.height).toBeGreaterThanOrEqual(44)
  expect(action.y + action.height).toBeLessThan(page.viewportSize().height)
  expect(hero.y).toBeLessThan(page.viewportSize().height)
  expect(Math.min(hero.height, page.viewportSize().height - hero.y)).toBeGreaterThan(hero.height * .65)
  await checkViewport(page)

  // Count initial UI assets and the selected hero as raw bytes. Native lazy
  // loading of the example and workflow media can vary by viewport.
  const heroAsset = await image.evaluate(item => new URL(item.currentSrc).pathname)
  const initial = [...site.files].filter(([path]) =>
    path === '/index.html' || path.startsWith('/assets/') || path === heroAsset)
  const initialBytes = initial.reduce((total, [, bytes]) => total + bytes, 0)
  expect(site.files.get(heroAsset)).toBeLessThan(210 * 1024)
  expect(initialBytes).toBeLessThan(315 * 1024)
  expect([...site.files.keys()].some(path => path.includes('study-worker'))).toBe(false)
  await info.attach('layout-check', { body: JSON.stringify({ action, hero, initialBytes }, null, 2),
    contentType: 'application/json' })

  await capture(page, info, 'landing-first-screen')
  await capture(page, info, 'landing', { fullPage: true })
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Skip to content' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('main')).toBeFocused()
  await checkAccessibility(page)
  expect(site.errors).toEqual([])
})

